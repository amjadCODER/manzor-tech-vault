create extension if not exists pgcrypto;

create table if not exists app_users (
  id text primary key,
  display_name text not null,
  role text not null default 'employee',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists organizations (
  id text primary key,
  name text not null,
  system_url text,
  official_email text,
  channel text,
  city text,
  manager text,
  phone text,
  domain text,
  relationship_start date,
  financial_commitment boolean not null default false,
  financial_amount numeric not null default 0,
  financial_note text,
  last_update timestamptz default now(),
  last_updated_by text,
  notes text,
  support_fund_status text default 'لم يبدأ',
  support_fund_progress integer default 0 check (support_fund_progress between 0 and 100),
  donors_ehsan_status text default 'لم يبدأ',
  donors_ehsan_progress integer default 0 check (donors_ehsan_progress between 0 and 100),
  other_funds_status text default 'لم يبدأ',
  other_funds_progress integer default 0 check (other_funds_progress between 0 and 100),
  created_at timestamptz not null default now()
);

alter table organizations add column if not exists support_fund_status text default 'لم يبدأ';
alter table organizations add column if not exists support_fund_progress integer default 0;
alter table organizations add column if not exists donors_ehsan_status text default 'لم يبدأ';
alter table organizations add column if not exists donors_ehsan_progress integer default 0;
alter table organizations add column if not exists other_funds_status text default 'لم يبدأ';
alter table organizations add column if not exists other_funds_progress integer default 0;

create table if not exists organization_sites (
  id uuid primary key default gen_random_uuid(),
  organization_id text not null references organizations(id) on delete cascade,
  title text not null,
  url text not null,
  note text,
  created_at timestamptz not null default now()
);
create index if not exists idx_organization_sites_org on organization_sites(organization_id);

create table if not exists organization_accounts (
  id uuid primary key default gen_random_uuid(),
  organization_id text not null references organizations(id) on delete cascade,
  provider text not null,
  username text,
  password text,
  url text,
  created_at_text text,
  created_at timestamptz not null default now()
);
create index if not exists idx_organization_accounts_org on organization_accounts(organization_id);

create table if not exists organization_files (
  id uuid primary key default gen_random_uuid(),
  organization_id text not null references organizations(id) on delete cascade,
  title text not null,
  category text not null default 'عام',
  file_path text not null,
  file_type text,
  uploaded_by text,
  created_at timestamptz not null default now()
);
create index if not exists idx_organization_files_org on organization_files(organization_id);

create table if not exists activity_log (
  id bigint generated by default as identity primary key,
  organization_id text references organizations(id) on delete set null,
  user_name text,
  action text not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_activity_log_org on activity_log(organization_id);

