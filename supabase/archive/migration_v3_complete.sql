-- النسخة الحالية تستخدم رمز موظف داخل التطبيق ولا تستخدم Supabase Auth بعد.
-- لذلك هذه السياسات تتيح التشغيل بالمفتاح العام. للانتاج الحساس ينصح لاحقا بتحويل الدخول إلى Supabase Auth.
alter table app_users enable row level security;
alter table organizations enable row level security;
alter table organization_sites enable row level security;
alter table organization_accounts enable row level security;
alter table organization_files enable row level security;
alter table activity_log enable row level security;

do $$ declare t text; begin
  foreach t in array array['app_users','organizations','organization_sites','organization_accounts','organization_files','activity_log'] loop
    execute format('drop policy if exists vault_anon_all on %I',t);
    execute format('create policy vault_anon_all on %I for all to anon using (true) with check (true)',t);
  end loop;
end $$;

drop policy if exists vault_storage_read on storage.objects;
drop policy if exists vault_storage_insert on storage.objects;
drop policy if exists vault_storage_update on storage.objects;
drop policy if exists vault_storage_delete on storage.objects;
create policy vault_storage_read on storage.objects for select to anon using (bucket_id='organization-files');
create policy vault_storage_insert on storage.objects for insert to anon with check (bucket_id='organization-files');
create policy vault_storage_update on storage.objects for update to anon using (bucket_id='organization-files') with check (bucket_id='organization-files');
create policy vault_storage_delete on storage.objects for delete to anon using (bucket_id='organization-files');
