-- الدخول الحالي برمز الموظف داخل التطبيق، لذلك تظل السياسات متاحة للمفتاح العام.
-- عند الانتقال إلى Supabase Auth يجب استبدال هذه السياسات بسياسات مستخدمين فعلية.
do $$
declare
  t text;
begin
  foreach t in array array[
    'app_users',
    'organizations',
    'organization_sites',
    'organization_accounts',
    'organization_files',
    'activity_log'
  ]
  loop
    execute format('drop policy if exists vault_app_access on manzor_vault.%I', t);
    execute format(
      'create policy vault_app_access on manzor_vault.%I for all to anon, authenticated using (true) with check (true)',
      t
    );
  end loop;
end $$;

