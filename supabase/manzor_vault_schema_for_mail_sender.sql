-- أسماء سياسات خاصة بـ Vault حتى لا تتعارض مع Mail Sender
drop policy if exists vault_files_read on storage.objects;
drop policy if exists vault_files_insert on storage.objects;
drop policy if exists vault_files_update on storage.objects;
drop policy if exists vault_files_delete on storage.objects;

create policy vault_files_read
on storage.objects for select
to anon, authenticated
using (bucket_id = 'vault-files');

create policy vault_files_insert
on storage.objects for insert
to anon, authenticated
with check (bucket_id = 'vault-files');

create policy vault_files_update
on storage.objects for update
to anon, authenticated
using (bucket_id = 'vault-files')
with check (bucket_id = 'vault-files');

create policy vault_files_delete
on storage.objects for delete
to anon, authenticated
using (bucket_id = 'vault-files');

